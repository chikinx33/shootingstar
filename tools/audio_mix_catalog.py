"""Generate runtime clip facts from the shipped Ogg clips, without changing them.

Needs soundfile: PYTHONPATH=D:/Programs/pylib python tools/audio_mix_catalog.py
"""
from pathlib import Path
import argparse
import re
import numpy as np
import soundfile as sf

root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
actual={}
lines=['// Generated by tools/audio_mix_catalog.py from the shipped Ogg clips.',
       'class AudioClip {', '  const AudioClip(this.milliseconds, this.rms, this.peak);',
       '  final int milliseconds;', '  final double rms, peak;', '}',
       'const audioClips = <String, AudioClip>{']
for p in sorted((root/'assets/audio').glob('*.ogg')):
    data,rate=sf.read(p,dtype='float64')
    duration=round(len(data)/rate*1000)
    lines.append(f"  '{p.stem}': AudioClip({duration}, {np.sqrt(np.mean(data**2)):.8f}, {np.max(abs(data)):.8f}),")
    actual[p.stem]=(duration,float(np.sqrt(np.mean(data**2))),float(np.max(abs(data))))
lines.append('};')
target=root/'lib/services/audio_clip_levels.dart'
if args.check:
    stored={m[1]:(int(m[2]),float(m[3]),float(m[4])) for m in re.finditer(r"'([^']+)': AudioClip\(\s*(\d+),\s*([\d.]+),\s*([\d.]+),?\s*\)",target.read_text())}
    assert stored.keys()==actual.keys(),'Audio clip catalog does not match current Ogg files'
    for name,values in actual.items():
        assert all(abs(a-b)<1e-7 for a,b in zip(values,stored[name])),name
    print('Audio mix catalog checked:',len(actual),'clips')
else:
    target.write_text('\n'.join(lines)+'\n',encoding='utf8')
    print('Audio mix catalog:',len(actual),'clips')
