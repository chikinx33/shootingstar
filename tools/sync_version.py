"""Keep the compiled footer and deployment metadata tied to pubspec.yaml."""
import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--version', help='New version including build number, e.g. 10.0.1+17')
parser.add_argument('--check', action='store_true', help='Read-only consistency check')
args = parser.parse_args()
if args.version and (args.check or not re.fullmatch(r'\d+\.\d+\.\d+\+\d+', args.version)):
    parser.error('--version requires major.minor.patch+build and cannot accompany --check')
pubspec = ROOT / 'pubspec.yaml'
source = pubspec.read_text(encoding='utf-8')
if args.version:
    source = re.sub(r'^version: .+$', 'version: ' + args.version, source, flags=re.M)
    pubspec.write_text(source, encoding='utf-8')
version, build = re.search(r'^version: (\d+\.\d+\.\d+)\+(\d+)\s*$', source, re.M).groups()
label = f'v{version}'
dart = (
    '// Generated by tools/sync_version.py from pubspec.yaml. Do not edit.\n'
    'abstract final class AppVersion {\n'
    f"  static const name = '{version}';\n"
    f"  static const build = '{build}';\n"
    f"  static const label = '{label}';\n"
    '}\n'
)
worker = ROOT / 'server/wrangler.jsonc'
worker_source = worker.read_text(encoding='utf-8')
worker_expected, count = re.subn(r'("APP_VERSION":\s*")[^"]+(")',
    lambda m: m[1] + version + m[2], worker_source)
assert count == 1, 'Expected exactly one APP_VERSION in wrangler.jsonc'
html = ROOT / 'web/index.html'
html_source = html.read_text(encoding='utf-8')
html_expected, count = re.subn(r'(?<=<!-- build-version:start -->).*?(?=<!-- build-version:end -->)',
    label, html_source)
assert count == 1, 'Expected one loading-screen build-version marker'
outputs = {ROOT / 'lib/app_version.dart': dart, worker: worker_expected, html: html_expected}
stale = []
for path, expected in outputs.items():
    if not path.exists() or path.read_text(encoding='utf-8') != expected:
        stale.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.write_text(expected, encoding='utf-8')
if args.check and stale:
    sys.exit('Version mismatch: ' + ', '.join(stale) + '. Run python tools/sync_version.py')
print(f'Version {"checked" if args.check else "synced"}: {label}')
